#!/usr/bin/env python3
"""Generates app/src/main/assets/cities.tsv, the offline city list for city search (#21).

Run:  python3 -I tools/cities/generate_cities.py [--cache DIR]
It downloads the sources below (or reuses them from --cache), so only generation needs the network; the
build uses the committed asset. Output is deterministic for the same inputs.

Sources and licences (credited on the About screen, #33):
- GeoNames cities15000 + countryInfo.txt, https://download.geonames.org/export/dump/ ,
  CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/). Names, coordinates, country, IANA time zone,
  population, and Arabic names taken from the `alternatenames` field.
- Natural Earth 10m populated places (`name_ar`), public domain,
  https://github.com/nvkelso/natural-earth-vector (geojson/ne_10m_populated_places.geojson).

Arabic name rule: Natural Earth's curated `name_ar` when it carries the same GeoNames id; otherwise the
first GeoNames alternate name written only in Arabic script that has no Persian/Urdu-only letters;
otherwise empty (the city is then found by its English name only).

Output: UTF-8, one header line starting with '#', then one row per city, sorted by population (largest
first), tab-separated: geonameid, name, Arabic name (may be empty), ISO 3166-1 alpha-2 country,
latitude, longitude (4 decimals, ~11 m), IANA time zone.
"""
import argparse
import io
import json
import os
import re
import tempfile
import urllib.request
import zipfile

GEONAMES = "https://download.geonames.org/export/dump/"
CITIES_URL = GEONAMES + "cities15000.zip"
COUNTRIES_URL = GEONAMES + "countryInfo.txt"
NE_URL = ("https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/"
          "geojson/ne_10m_populated_places.geojson")

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "app", "src", "main", "assets",
                   "cities.tsv")

ARABIC = re.compile(r"^[؀-ۿ\s\-]+$")
# Letters used in Persian, Urdu, Pashto, Kurdish etc. but not in Arabic.
NON_ARABIC_LETTERS = re.compile(
    "[پچژگکیۀٹڈڑںےھہۃە"
    "ۆۇۈۋېڕڵێځڅډړږښڼګ"
    "ۍڠڤڥ]")
DIACRITICS = re.compile("[ً-ٰٟـ]")


def fetch(url, cache):
    path = os.path.join(cache, url.rsplit("/", 1)[1])
    if not os.path.exists(path):
        print("downloading", url)
        urllib.request.urlretrieve(url, path)
    return path


def clean(name):
    return " ".join(DIACRITICS.sub("", name).split())


def arabic_from_alternates(alternates):
    for name in alternates.split(","):
        name = name.strip()
        if name and ARABIC.match(name) and not NON_ARABIC_LETTERS.search(name):
            return clean(name)
    return ""


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--cache", help="directory holding (or receiving) the downloaded sources")
    parser.add_argument("--out", default=OUT)
    args = parser.parse_args()
    cache = args.cache or tempfile.mkdtemp(prefix="mawaqeet-cities-")
    os.makedirs(cache, exist_ok=True)

    countries = set()
    with open(fetch(COUNTRIES_URL, cache), encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            countries.add(line.split("\t")[0])

    with open(fetch(NE_URL, cache), encoding="utf-8") as f:
        features = json.load(f)["features"]
    ne_arabic = {}
    for feature in features:
        p = {k.lower(): v for k, v in feature["properties"].items()}
        gid, name_ar = p.get("geonamesid"), (p.get("name_ar") or "").strip()
        if gid and int(gid) > 0 and name_ar:
            ne_arabic[int(gid)] = clean(name_ar)

    rows = []
    with zipfile.ZipFile(fetch(CITIES_URL, cache)) as z:
        text = io.TextIOWrapper(z.open("cities15000.txt"), encoding="utf-8")
        for line in text:
            c = line.rstrip("\n").split("\t")
            gid, name, alternates, lat, lon, cc, population, zone = (
                int(c[0]), c[1], c[3], float(c[4]), float(c[5]), c[8], int(c[14] or 0), c[17])
            if cc not in countries or not zone:
                continue
            arabic = ne_arabic.get(gid) or arabic_from_alternates(alternates)
            rows.append((-population, gid, name, arabic, cc, lat, lon, zone))
    rows.sort()

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as out:
        out.write("# mawaqeet-cities-v1 GeoNames cities15000 (CC BY 4.0, geonames.org) + Natural Earth name_ar "
                  "(public domain); generated by tools/cities/generate_cities.py\n")
        for _, gid, name, arabic, cc, lat, lon, zone in rows:
            out.write(f"{gid}\t{name}\t{arabic}\t{cc}\t{lat:.4f}\t{lon:.4f}\t{zone}\n")
    with_arabic = sum(1 for r in rows if r[3])
    print(f"{len(rows)} cities, {with_arabic} with Arabic names -> {os.path.normpath(args.out)}")


if __name__ == "__main__":
    main()
